USE cafeconecta;
SET NAMES utf8mb4;

-- Los productores pueden no tener correo (HU-01).
ALTER TABLE persona MODIFY correo VARCHAR(100) NULL;

-- Perfiles nuevos (solo se crean si no existen).
INSERT INTO perfil (descripc, estado)
  SELECT 'Productor', 'Activo' FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM perfil WHERE descripc = 'Productor');
INSERT INTO perfil (descripc, estado)
  SELECT 'Comprador', 'Activo' FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM perfil WHERE descripc = 'Comprador');

-- ---------------------------------------------------------------------
-- PARCIAL II · Departamentos y municipios (listas desplegables de Fincas)
-- ---------------------------------------------------------------------
CREATE TABLE departamento (
  iddepartamento INT(11)     NOT NULL,
  nombre         VARCHAR(60) NOT NULL,
  PRIMARY KEY (iddepartamento),
  UNIQUE KEY uq_departamento_nombre (nombre)
) ENGINE=InnoDB;

CREATE TABLE municipio (
  idmunicipio    INT(11)     NOT NULL AUTO_INCREMENT,
  nombre         VARCHAR(80) NOT NULL,
  iddepartamento INT(11)     NOT NULL,
  PRIMARY KEY (idmunicipio),
  UNIQUE KEY uq_municipio (iddepartamento, nombre),
  CONSTRAINT fk_municipio_departamento FOREIGN KEY (iddepartamento) REFERENCES departamento (iddepartamento)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- HU-01 · Productores cafeteros
-- Usa la misma programación de persona: los datos personales (nombres,
-- celular, dirección, fecha de nacimiento y correo) se guardan en persona,
-- y aquí quedan el documento (llave primaria) y el estado del productor.
-- ---------------------------------------------------------------------
CREATE TABLE productor (
  documento  VARCHAR(12) NOT NULL,
  idpersona  INT(11)     NOT NULL,
  estado     VARCHAR(20) NOT NULL DEFAULT 'Activo',
  PRIMARY KEY (documento),
  UNIQUE KEY uq_productor_persona (idpersona),
  CONSTRAINT fk_productor_persona FOREIGN KEY (idpersona) REFERENCES persona (Idpersona),
  CONSTRAINT ck_productor_estado CHECK (estado IN ('Activo', 'Inactivo'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- HU-02 · Fincas
-- ---------------------------------------------------------------------
CREATE TABLE finca (
  codigof      VARCHAR(15)   NOT NULL,
  nombre       VARCHAR(80)   NOT NULL,
  area         DECIMAL(10,2) NOT NULL,
  temperatura  DECIMAL(4,1)  NOT NULL,
  telefono     VARCHAR(10)   NOT NULL,
  direccion    VARCHAR(120)  NOT NULL,
  idmunicipio  INT(11)       NOT NULL,
  documento    VARCHAR(12)   NOT NULL,
  estado       VARCHAR(20)   NOT NULL DEFAULT 'Activo',
  PRIMARY KEY (codigof),
  KEY fk_finca_municipio (idmunicipio),
  KEY fk_finca_productor (documento),
  CONSTRAINT fk_finca_municipio FOREIGN KEY (idmunicipio) REFERENCES municipio (idmunicipio),
  CONSTRAINT fk_finca_productor FOREIGN KEY (documento) REFERENCES productor (documento),
  CONSTRAINT ck_finca_area CHECK (area > 0),
  CONSTRAINT ck_finca_temperatura CHECK (temperatura BETWEEN 5 AND 35),
  CONSTRAINT ck_finca_estado CHECK (estado IN ('Activo', 'Inactivo'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- HU-03 · Cooperativas
-- ---------------------------------------------------------------------
CREATE TABLE cooperativa (
  nit        VARCHAR(12)  NOT NULL,
  nombre     VARCHAR(100) NOT NULL,
  direccion  VARCHAR(120) NOT NULL,
  telefono   VARCHAR(10)  NOT NULL,
  correo     VARCHAR(100) NOT NULL,
  estado     VARCHAR(20)  NOT NULL DEFAULT 'Activo',
  PRIMARY KEY (nit),
  UNIQUE KEY uq_cooperativa_nombre (nombre),
  UNIQUE KEY uq_cooperativa_correo (correo),
  CONSTRAINT ck_cooperativa_estado CHECK (estado IN ('Activo', 'Inactivo'))
) ENGINE=InnoDB;

-- Los usuarios con perfil Comprador representan a una cooperativa.
ALTER TABLE usuario
  ADD COLUMN nit VARCHAR(12) NULL AFTER idpersona,
  ADD CONSTRAINT fk_usuario_cooperativa FOREIGN KEY (nit) REFERENCES cooperativa (nit);

-- ---------------------------------------------------------------------
-- HU-04 · Asociación de productores a cooperativas (muchos a muchos)
-- estado: Pendiente (solicitada por un comprador), Activo, Inactivo
-- (desasociada, con fecha de retiro) o Rechazada.
-- ---------------------------------------------------------------------
CREATE TABLE asociacion (
  idasociacion      INT(11)     NOT NULL AUTO_INCREMENT,
  documento         VARCHAR(12) NOT NULL,
  nit               VARCHAR(12) NOT NULL,
  fecha_solicitud   DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_afiliacion  DATE        DEFAULT NULL,
  fecha_retiro      DATE        DEFAULT NULL,
  idusuario_solicita INT(11)    DEFAULT NULL,
  estado            VARCHAR(20) NOT NULL DEFAULT 'Activo',
  PRIMARY KEY (idasociacion),
  KEY fk_asociacion_productor (documento),
  KEY fk_asociacion_cooperativa (nit),
  CONSTRAINT fk_asociacion_productor FOREIGN KEY (documento) REFERENCES productor (documento),
  CONSTRAINT fk_asociacion_cooperativa FOREIGN KEY (nit) REFERENCES cooperativa (nit),
  CONSTRAINT fk_asociacion_usuario FOREIGN KEY (idusuario_solicita) REFERENCES usuario (Idusuario),
  CONSTRAINT ck_asociacion_estado CHECK (estado IN ('Pendiente', 'Activo', 'Inactivo', 'Rechazada'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- HU-05 · Tipos de variedades de café
-- ---------------------------------------------------------------------
CREATE TABLE variedad (
  codigotv     VARCHAR(10) NOT NULL,
  descripcion  VARCHAR(50) NOT NULL,
  imagen       MEDIUMBLOB  NOT NULL,
  imagen_tipo  VARCHAR(10) NOT NULL,
  estado       VARCHAR(20) NOT NULL DEFAULT 'Activo',
  PRIMARY KEY (codigotv),
  UNIQUE KEY uq_variedad_descripcion (descripcion),
  CONSTRAINT ck_variedad_estado CHECK (estado IN ('Activo', 'Inactivo'))
) ENGINE=InnoDB;

